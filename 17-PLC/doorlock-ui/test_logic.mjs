import assert from 'node:assert/strict';
import { DoorLock } from './logic.mjs';
let time = 0;
const events = [];
const lock = new DoorLock({ now: () => time, onChange: e => events.push(e) });
for (const n of [3, 1, 5, 2]) lock.input(n);
assert.equal(lock.phase, 'opening');
time = 1300; lock.tick();
assert.equal(lock.phase, 'open');
time = 6299; lock.tick();
assert.equal(lock.phase, 'open');
time = 6300; lock.tick();
assert.equal(lock.phase, 'closing');
lock.input(3); assert.equal(lock.entered.join(''), '3152');
time = 7600; lock.tick();
assert.equal(lock.phase, 'locked');
assert.deepEqual(lock.entered, []);
for (const n of [1, 1, 1, 1]) lock.input(n);
assert.equal(lock.phase, 'denied');
time = 9000; lock.tick();
assert.equal(lock.phase, 'locked');
for (const n of [3, 1, 5, 2]) lock.input(n);
lock.close(); assert.equal(lock.phase, 'closing');
time += 1300; lock.tick();
lock.input(9); lock.input(-1); assert.equal(lock.entered.length, 0);
lock.input(3); lock.clear(); assert.equal(lock.entered.length, 0);
console.log('PASS: PIN 3152, wrong PIN, 5-second auto-close, manual close, input guard, clear');

const editable = new DoorLock({ now: () => time });
editable.backspace();
assert.deepEqual(editable.entered, []);
for (const n of [3, 1, 4]) editable.input(n);
editable.backspace();
assert.equal(editable.entered.join(''), '31');
editable.input(5); editable.input(2);
assert.equal(editable.phase, 'opening');
editable.backspace(); editable.clear();
assert.equal(editable.phase, 'opening');
assert.equal(editable.entered.join(''), '3152');
const retry = new DoorLock({ now: () => time });
for (const n of [3, 1, 5, 1]) retry.input(n);
assert.equal(retry.phase, 'denied');
retry.backspace();
assert.equal(retry.phase, 'locked');
assert.equal(retry.deadline, 0);
assert.equal(retry.entered.join(''), '315');
retry.input(2);
assert.equal(retry.phase, 'opening');
const reset = new DoorLock({ now: () => time });
reset.input(3); reset.input(1); reset.clear();
assert.deepEqual(reset.entered, []);
for (const n of [1, 1, 1, 1]) reset.input(n);
reset.clear();
assert.equal(reset.phase, 'locked');
assert.equal(reset.deadline, 0);
assert.deepEqual(reset.entered, []);
console.log('PASS: delete last digit, correct partial PIN, edit denied PIN, clear partial/denied PIN, no edits during opening');

const settings = new DoorLock({ now: () => time });
let persisted = '';
assert.notEqual(settings.changePassword('1111', '2045', '2045'), '');
assert.notEqual(settings.changePassword('3152', '2468', '2468'), '');
assert.notEqual(settings.changePassword('3152', '123', '123'), '');
assert.notEqual(settings.changePassword('3152', '2045', '2044'), '');
assert.notEqual(settings.changePassword('3152', '3152', '3152'), '');
assert.equal(settings.password, '3152');
assert.notEqual(settings.changePassword('3152', '2045', '2045', () => { throw new Error('quota'); }), '');
assert.equal(settings.password, '3152');
settings.input(3);
assert.equal(settings.changePassword('3152', '2045', '2045', pin => { persisted = pin; }), '');
assert.equal(settings.password, '2045');
assert.deepEqual(settings.entered, []);
assert.equal(persisted, '2045');
const reloaded = new DoorLock({ password: persisted, now: () => time });
for (const n of [3, 1, 5, 2]) reloaded.input(n);
assert.equal(reloaded.phase, 'denied');
reloaded.clear();
for (const n of [2, 0, 4, 5]) reloaded.input(n);
assert.equal(reloaded.phase, 'opening');
assert.notEqual(reloaded.changePassword('2045', '1111', '1111'), '');
assert.equal(reloaded.password, '2045');
assert.equal(new DoorLock({ password: 'broken' }).password, '3152');
assert.equal(new DoorLock({ password: 1234 }).password, '3152');
console.log('PASS: password validation, current PIN, confirmation, save failure, new PIN, old PIN rejected, saved PIN reload, change guard');
